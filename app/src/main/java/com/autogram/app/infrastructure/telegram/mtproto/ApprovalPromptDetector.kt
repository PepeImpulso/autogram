package com.autogram.app.infrastructure.telegram.mtproto

import org.drinkless.tdlib.TdApi

/**
 * Recognizes the exec-approval request that the Hermes gateway posts when the
 * agent wants to run a command that needs the owner's OK. Autogram speaks a
 * short pointer to Telegram for these messages instead of reading the command
 * (issue #87); the original Telegram message is never touched.
 *
 * Detection is deliberately narrow. A message is an approval prompt only when
 * ALL of the following hold:
 *
 *  1. It arrived on a route the user configured as an assistant (a pinned
 *     circle). Autogram has no per-sender allow-list; the pinned chat/topic is
 *     the configuration, and [MtprotoReceiverService] only reaches this code
 *     after the route matched. Nothing else is ever inspected.
 *  2. The sender is a user account that is a bot ([candidateSenderUserId] plus
 *     the `UserTypeBot` check in the service), and in a private chat that user
 *     is the chat partner. An approval-looking text typed by a human, or sent
 *     by someone else in a shared group, is read as a normal message.
 *  3. The message shape matches what Hermes really sends ([isApprovalPrompt]):
 *       a. Button card: an inline keyboard whose buttons are callback buttons
 *          with Hermes' approval payloads `ea:<choice>:<id>`, containing at
 *          least the `once` and `deny` choices. Hermes' Telegram adapter builds
 *          them in `_send_exec_approval_prompt`, with callback data
 *          `ea:{once|session|always|deny}:{counter}`. This is the primary
 *          signal and does not depend on the card wording.
 *       b. Text fallback (sent when the card fails, e.g. too long): the text
 *          starts with Hermes' fixed header ("Hermes wants to run a command
 *          that needs your OK", or the "Smart DENY" header) AND contains both
 *          the typed `/approve` and `/deny` instructions AND the deadline
 *          sentence ("... will NOT run"). Generated by
 *          `_format_exec_approval_fallback` in the Hermes gateway.
 *
 * Not used on purpose: the words "authorize"/"approve" alone, code blocks or
 * monospace entities (normal replies contain them), and Hermes' internal
 * `is_approval_prompt` metadata flag, which is not part of what Telegram
 * delivers to a user client.
 *
 * The text fallback carries no keyboard, so (b) is its only signal; it needs
 * three independent matches to avoid reacting to ordinary prose that merely
 * mentions approving.
 */
internal object ApprovalPromptDetector {

    private val APPROVAL_CALLBACK = Regex("^ea:(once|session|always|deny):\\d+$")

    // U+26A0 (warning sign), optionally followed by the emoji variation
    // selector, optionally followed by literal bold markers if Telegram
    // formatting fell back to plain text.
    private val FALLBACK_HEADER = Regex(
        "^\\s*\\u26A0\\uFE0F?\\s*\\*{0,2}\\s*" +
            "(?:Hermes wants to run a command that needs your OK" +
            "|Smart DENY \\u2014 owner override for one operation)"
    )
    private const val FALLBACK_APPROVE = "/approve"
    private const val FALLBACK_DENY = "/deny"
    private const val FALLBACK_DEADLINE = "NOT run"

    /** Message-shape check only; sender checks are separate (see class doc). */
    fun isApprovalPrompt(text: String, replyMarkup: TdApi.ReplyMarkup?): Boolean =
        hasApprovalKeyboard(replyMarkup) || isTextFallback(text)

    /**
     * User id to verify as a bot, or null when the sender can never qualify:
     * outgoing messages, anonymous/chat senders, and in a private chat (positive
     * chat id) any sender other than the chat partner.
     */
    fun candidateSenderUserId(message: TdApi.Message): Long? {
        if (message.isOutgoing) return null
        val sender = message.senderId as? TdApi.MessageSenderUser ?: return null
        if (message.chatId > 0 && sender.userId != message.chatId) return null
        return sender.userId
    }

    internal fun hasApprovalKeyboard(replyMarkup: TdApi.ReplyMarkup?): Boolean {
        val keyboard = replyMarkup as? TdApi.ReplyMarkupInlineKeyboard ?: return false
        val choices = keyboard.rows.orEmpty()
            .flatMap { it.orEmpty().toList() }
            .mapNotNull { button ->
                val callback = button.type as? TdApi.InlineKeyboardButtonTypeCallback
                    ?: return@mapNotNull null
                val data = callback.data ?: return@mapNotNull null
                APPROVAL_CALLBACK.matchEntire(String(data, Charsets.UTF_8))?.groupValues?.get(1)
            }
            .toSet()
        return "once" in choices && "deny" in choices
    }

    internal fun isTextFallback(text: String): Boolean =
        FALLBACK_HEADER.containsMatchIn(text) &&
            text.contains(FALLBACK_APPROVE) &&
            text.contains(FALLBACK_DENY) &&
            text.contains(FALLBACK_DEADLINE)
}
